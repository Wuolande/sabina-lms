/**
 * Auto-detects client timezone safely.
 */
export function detectUserTimezone(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || 'Africa/Nairobi';
  } catch {
    return 'Africa/Nairobi';
  }
}

/**
 * Returns a list of years for graduation/experience dropdowns.
 */
export function getYearOptions(futureYears = 6, pastYears = 60): string[] {
  const current = new Date().getFullYear();
  const start = current + futureYears;
  const count = futureYears + pastYears;
  return Array.from({ length: count }, (_, i) => String(start - i));
}

